static bool requests_dem(const mln_resource_request_info* request) {
  static const char fragment[] = "/dem/";
  const size_t length = sizeof(fragment) - 1;
  const mln_buffer_view url = request->requested_url;
  for (size_t start = 0; start + length <= url.size; start += 1) {
    if (memcmp(url.data + start, fragment, length) == 0) {
      return true;
    }
  }
  return false;
}

static void serve_dem(
  void* user_data, const mln_resource_request_info* request,
  mln_resource_request handle
) {
  const mln_test_dem_tile* tile = user_data;
  mln_resource_response response = {
    .size = sizeof(mln_resource_response),
    .status = MLN_RESOURCE_RESPONSE_STATUS_NO_CONTENT,
  };
  if (requests_dem(request)) {
    response.status = MLN_RESOURCE_RESPONSE_STATUS_OK;
    response.bytes = tile->bytes;
    response.byte_count = tile->size;
  }
  mln_test_request_answer(handle, &response);
}

mln_resource_provider mln_test_dem_provider(const mln_test_dem_tile* tile) {
  return (mln_resource_provider){
    .size = sizeof(mln_resource_provider),
    .callback = serve_dem,
    // The provider only reads the tile.
    .user_data = (void*)tile,
  };
}
